const BAND_SEQUENCE = ['critical', 'critical', 'critical', 'critical', 'critical', 'rebuilding', 'rebuilding', 'rebuilding', 'rebuilding', 'rebuilding', 'ready', 'ready', 'ready', 'ready', 'ready'];

function material(title, body) {
  return `${title}\n\n${body}\n\n评审时只使用上述材料中已经出现的事实，不要假设未提供的数字、用户反馈或业务背景。`;
}

function buildCases(roleId, definitions) {
  return definitions.map(([id, focus, body], index) => ({
    id: `${roleId}-${id}`,
    roleId,
    reviewMode: 'general',
    expectedBand: BAND_SEQUENCE[index],
    focus,
    materialText: material(focus, body)
  }));
}

